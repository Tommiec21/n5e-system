/**
 * Build the shared rules core bundle (SHARED1): dist/n5e-core/ and dist/n5e-core.zip.
 *
 *   module/rules, module/config   the core (core.json roots), unchanged paths
 *   tests/core                    the core tests and their setup (run with `npm test` inside the bundle)
 *   index.mjs                     every rules file as a namespace, plus config, setRuleProvider, setHost
 *   package.json                  name n5e-core, version = the System version
 *   CORE_API.md                   the exported names of each rules file
 *
 * Run by tools/release.mjs after the System zip, so every System release ships its core. The Module
 * checks for a new core once a day (King 2026-11-14, Q-SH3).
 */
import fs from "node:fs";
import path from "node:path";
import archiver from "archiver";

const ROOT = path.resolve(import.meta.dirname, "..");
const DIST = path.join(ROOT, "dist");
const OUT = path.join(DIST, "n5e-core");
const core = JSON.parse(fs.readFileSync(path.join(ROOT, "core.json"), "utf8"));
const system = JSON.parse(fs.readFileSync(path.join(ROOT, "system.json"), "utf8"));
const camel = file => path.basename(file, ".mjs").replace(/-([a-z])/g, (m, c) => c.toUpperCase());

/** Exported names of a module's source (export function/const/class/let, export { a, b as c }). */
export function exportedNames(src) {
  const names = new Set();
  for ( const m of src.matchAll(/export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/g) ) names.add(m[1]);
  for ( const m of src.matchAll(/export\s*\{([^}]*)\}/g) ) {
    for ( const part of m[1].split(",") ) {
      const name = part.trim().split(/\s+as\s+/).pop()?.trim();
      if ( name ) names.add(name);
    }
  }
  if ( /export\s+default\b/.test(src) ) names.add("default");
  return [...names].sort();
}

export async function buildCore() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  for ( const r of [...core.roots, core.tests] ) fs.cpSync(path.join(ROOT, r), path.join(OUT, r), { recursive: true });

  const rulesDir = path.join(ROOT, "module/rules");
  const files = fs.readdirSync(rulesDir).filter(f => f.endsWith(".mjs")).sort();
  const index = [
    "// N5e shared rules core (generated by tools/build-core.mjs). Each rules file is a namespace.",
    "export { setRuleProvider, rule } from \"./module/rules/settings.mjs\";",
    "export { setHost, n5eConfig } from \"./module/rules/host.mjs\";",
    "export { default as config } from \"./module/config/index.mjs\";",
    ...files.map(f => `export * as ${camel(f)} from "./module/rules/${f}";`)
  ];
  fs.writeFileSync(path.join(OUT, "index.mjs"), `${index.join("\n")}\n`);

  const api = ["# N5e core API", "", `Version ${system.version}. Generated by \`tools/build-core.mjs\` from \`module/rules\`.`, "",
    "Hosts call `setRuleProvider(key => value)` and `setHost({config: () => registry})` before using the core.", ""];
  for ( const f of files ) {
    const names = exportedNames(fs.readFileSync(path.join(rulesDir, f), "utf8"));
    api.push(`## ${camel(f)} (\`module/rules/${f}\`)`, "", names.length ? names.map(n => `\`${n}\``).join(", ") : "(no exports)", "");
  }
  fs.writeFileSync(path.join(OUT, "CORE_API.md"), api.join("\n"));

  const pkg = { name: "n5e-core", version: system.version, private: true, type: "module", exports: { ".": "./index.mjs" },
    description: core.description, scripts: { test: "node --import ./tests/core/setup.mjs --test \"tests/core/**/*.test.mjs\"" } };
  fs.writeFileSync(path.join(OUT, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`);
  fs.copyFileSync(path.join(ROOT, "core.json"), path.join(OUT, "core.json"));
  if ( fs.existsSync(path.join(ROOT, "LICENSE")) ) fs.copyFileSync(path.join(ROOT, "LICENSE"), path.join(OUT, "LICENSE"));

  const output = fs.createWriteStream(path.join(DIST, "n5e-core.zip"));
  const zip = archiver("zip", { zlib: { level: 9 } });
  zip.pipe(output);
  zip.directory(OUT, "n5e-core");
  await zip.finalize();
  await new Promise(r => output.on("close", r));
  console.log(`dist/n5e-core.zip (${(zip.pointer() / 1024).toFixed(0)} KB): core ${system.version}, ${files.length} rules files`);
}

if ( import.meta.url === `file://${process.argv[1]}` ) await buildCore();
