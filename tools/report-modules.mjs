/**
 * Writes docs/generated/module-index.md: every module file, its one-line purpose (first doc-comment
 * sentence) and its exported names. Run after adding or renaming exports: node tools/report-modules.mjs
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const files = [];
const walk = dir => {
  for ( const name of readdirSync(dir).sort() ) {
    const path = join(dir, name);
    if ( statSync(path).isDirectory() ) walk(path);
    else if ( name.endsWith(".mjs") ) files.push(path);
  }
};
walk(join(root, "module"));

const purpose = text => {
  const doc = text.match(/\/\*\*([\s\S]*?)\*\//);
  if ( !doc ) return "";
  const line = doc[1].split("\n").map(l => l.replace(/^\s*\*\s?/, "").trim()).filter(Boolean).join(" ");
  const first = line.split(/(?<=\.)\s/)[0] ?? "";
  return first.length > 160 ? `${first.slice(0, 157)}...` : first;
};
const exportsOf = text => {
  const names = new Set();
  for ( const m of text.matchAll(/^export\s+(?:default\s+)?(?:async\s+)?(?:function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)/gm) ) names.add(m[1]);
  for ( const m of text.matchAll(/^export\s*\{([^}]*)\}/gm) ) {
    for ( const part of m[1].split(",") ) {
      const name = part.trim().split(/\s+as\s+/).pop();
      if ( name ) names.add(name);
    }
  }
  return [...names];
};

const groups = new Map();
for ( const file of files ) {
  const rel = relative(root, file);
  const dir = rel.split("/").slice(0, -1).join("/");
  const text = readFileSync(file, "utf8");
  if ( !groups.has(dir) ) groups.set(dir, []);
  groups.get(dir).push({ rel, lines: text.split("\n").length, purpose: purpose(text), exports: exportsOf(text) });
}

const out = ["# Module index (generated)", "",
  "Generated by `node tools/report-modules.mjs`. One row per file: purpose (first doc-comment sentence) and exported names.",
  "Regenerate after adding or renaming exports; do not edit by hand.", ""];
for ( const [dir, entries] of groups ) {
  out.push(`## ${dir}`, "", "| File | Lines | Purpose | Exports |", "| --- | ---: | --- | --- |");
  for ( const e of entries ) {
    const cell = s => s.replace(/\|/g, "\\|");
    out.push(`| \`${e.rel.split("/").pop()}\` | ${e.lines} | ${cell(e.purpose)} | ${e.exports.map(n => `\`${n}\``).join(", ")} |`);
  }
  out.push("");
}
mkdirSync(join(root, "docs/generated"), { recursive: true });
writeFileSync(join(root, "docs/generated/module-index.md"), out.join("\n"));
console.log(`module-index.md: ${files.length} files, ${[...groups.values()].flat().reduce((t, e) => t + e.exports.length, 0)} exports`);
