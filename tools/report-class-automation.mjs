/**
 * The review table for each class automation table (STD6d): docs/classes/<class>-automation.md.
 * Core features first, then each subclass, by level, then name. For each feature: its status, what
 * is automated (from the applied data, rules/automation-summary.mjs) and what stays at the table.
 *
 *   node tools/report-class-automation.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { automationOf, STATUS_LABELS } from "../module/rules/automation-summary.mjs";
import { automationTables, clanTables, clanItems } from "./content/apply-automation.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name))
  : e.name.endsWith(".json") ? [path.join(d, e.name)] : []);
const docs = walk(path.join(ROOT, "packs/_source/features")).map(f => JSON.parse(fs.readFileSync(f, "utf8")));
const folders = new Map(docs.filter(d => !d.system).map(d => [d._id, d.name]));
const cell = s => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const STATUS = { ...STATUS_LABELS, none: "No mechanics" };

fs.mkdirSync(path.join(ROOT, "docs/classes"), { recursive: true });
for ( const t of automationTables() ) {
  const feats = docs.filter(d => d.system?.requirement?.class === t.class);
  const group = d => {
    const f = folders.get(d.folder) ?? "";
    const sub = d.name.match(/\(([^)]+)\)$/)?.[1];
    return sub && !/level benefit/.test(sub) ? sub : /core|features/i.test(f) || !f ? "Core" : f;
  };
  const groups = [...new Set(feats.map(group))].sort((a, b) => (a === "Core" ? -1 : b === "Core" ? 1 : a.localeCompare(b)));
  const counts = Object.fromEntries(Object.keys(STATUS).map(k => [k, 0]));
  const lines = [`# ${t.class} automation review (STD6d)`, "",
    `Generated by \`node tools/report-class-automation.mjs\` from \`content/automation/${t.file}\` as applied to the features. Spec: \`docs/STD6d_SPEC.md\`.`, ""];
  const body = [];
  for ( const g of groups ) {
    body.push(`## ${g}`, "", "| Level | Feature | Status | Automated | At the table |", "| ---: | --- | --- | --- | --- |");
    const rows = feats.filter(d => group(d) === g).sort((a, b) => (a.system.requirement.level ?? 0) - (b.system.requirement.level ?? 0) || a.name.localeCompare(b.name));
    for ( const d of rows ) {
      const status = t.features?.[d.system.identifier]?.status ?? "none";
      counts[status]++;
      const a = automationOf(d);
      body.push(`| ${d.system.requirement.level ?? ""} | ${cell(d.name)} | ${STATUS[status]} | ${cell(a.channels.map(c => `${c.kind}: ${c.label}${c.summary && c.summary !== c.label ? ` (${c.summary})` : ""}`).join("; ")) || "—"} | ${cell(a.notes.map(n => n.text).join(" ")) || "—"} |`);
    }
    body.push("");
  }
  lines.push(`${feats.length} features: ${Object.entries(counts).filter(([, n]) => n).map(([k, n]) => `${n} ${STATUS[k].toLowerCase()}`).join(", ")}.`, "", ...body);
  fs.writeFileSync(path.join(ROOT, "docs/classes", `${t.class}-automation.md`), `${lines.join("\n")}\n`);
  console.log(`✓ docs/classes/${t.class}-automation.md`);
}

// STD6e: one review table per clan (docs/clans/<clan>-automation.md): features and options by level,
// then stances, then Hijutsu by rank.
fs.mkdirSync(path.join(ROOT, "docs/clans"), { recursive: true });
const RANKS = ["E", "D", "C", "B", "A", "S"];
for ( const t of clanTables() ) {
  const items = [...clanItems(t.clan).values()].map(x => x.doc);
  const kindOf = d => (d.type === "jutsu" ? "Hijutsu" : d.type === "stance" ? "Stances" : d.system?.category === "clanFeatureOption" ? "Feature options" : "Features");
  const counts = Object.fromEntries(Object.keys(STATUS).map(k => [k, 0]));
  const body = [];
  for ( const g of ["Features", "Feature options", "Stances", "Hijutsu"] ) {
    const rows = items.filter(d => kindOf(d) === g).sort((a, b) => (g === "Hijutsu"
      ? RANKS.indexOf(a.system.rank) - RANKS.indexOf(b.system.rank) : (a.system.requirement?.level ?? 0) - (b.system.requirement?.level ?? 0)) || a.name.localeCompare(b.name));
    if ( !rows.length ) continue;
    body.push(`## ${g}`, "", `| ${g === "Hijutsu" ? "Rank" : "Level"} | Item | Status | Automated | At the table |`, "| ---: | --- | --- | --- | --- |");
    for ( const d of rows ) {
      const status = t.features?.[d.system.identifier]?.status ?? "none";
      counts[status]++;
      const a = automationOf(d);
      body.push(`| ${g === "Hijutsu" ? d.system.rank : d.system.requirement?.level ?? ""} | ${cell(d.name)} | ${STATUS[status]} | ${cell(a.channels.map(c => `${c.kind}: ${c.label}${c.summary && c.summary !== c.label ? ` (${c.summary})` : ""}`).join("; ")) || "—"} | ${cell(a.notes.map(n => n.text).join(" ")) || "—"} |`);
    }
    body.push("");
  }
  const lines = [`# ${t.clan} automation review (STD6e)`, "",
    `Generated by \`node tools/report-class-automation.mjs\` from \`content/automation/${t.file}\` as applied to the clan's items. Spec: \`docs/STD6e_SPEC.md\`.`, "",
    `${items.length} items: ${Object.entries(counts).filter(([, n]) => n).map(([k, n]) => `${n} ${STATUS[k].toLowerCase()}`).join(", ")}.`, "", ...body];
  fs.writeFileSync(path.join(ROOT, "docs/clans", `${t.clan}-automation.md`), `${lines.join("\n")}\n`);
  console.log(`✓ docs/clans/${t.clan}-automation.md`);
}
