/**
 * Rider coverage (CARD1d): every feature or feat whose text reads like a rider ("when you hit", "on a
 * failed save", "when you deal damage", "as part of casting"...), by class (or feat/clan), marked
 * authored or not. Writes docs/generated/rider-coverage.md. Authoring: docs/RIDERS.md.
 *
 *   node tools/report-riders.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { riderTables } from "./content/apply-riders.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCES = ["packs/_source/features", "packs/_source/feats"].map(p => path.join(ROOT, p)).filter(p => fs.existsSync(p));
const TRIGGER = /(fail(s|ed)? (on |its |their |the |a )?(saving throw|save)|on a fail|when you (hit|deal|cast)|when a creature fails|on a (hit|successful hit|critical)|deals? damage to|as part of casting|when you would (deal|cast|hit))/i;

const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(d => (d.isDirectory() ? walk(path.join(dir, d.name))
  : d.name.endsWith(".json") && !d.name.startsWith("_folder") ? [path.join(dir, d.name)] : []));
const text = html => String(html ?? "").replace(/<[^>]+>/g, " ").replace(/&[a-z#0-9]+;/gi, " ").replace(/\s+/g, " ").trim();

export function coverage() {
  const authored = new Set(riderTables().map(e => e.identifier));
  const rows = [];
  for ( const dir of SOURCES ) for ( const f of walk(dir) ) {
    const d = JSON.parse(fs.readFileSync(f, "utf8"));
    const s = d.system ?? {};
    const body = text(s.description);
    const hit = body.split(/(?<=[.!?])\s+/).find(x => TRIGGER.test(x));
    if ( !hit ) continue;
    const group = s.requirement?.class || (dir.endsWith("feats") ? "feats" : s.requirement?.clan ? `clan: ${s.requirement.clan}` : "other");
    rows.push({ group, level: s.requirement?.level ?? 0, name: d.name, id: s.identifier, authored: authored.has(s.identifier), line: hit.slice(0, 160) });
  }
  return rows.sort((a, b) => a.group.localeCompare(b.group) || a.level - b.level || a.name.localeCompare(b.name));
}

if ( import.meta.url === `file://${process.argv[1]}` ) {
  const rows = coverage();
  const groups = [...new Set(rows.map(r => r.group))];
  const out = ["# Rider coverage", "", "Generated by `node tools/report-riders.mjs`. Features and feats whose text reads like a rider, by class (level order). Author riders in `content/riders/<class>.json` (see `docs/RIDERS.md`), then `npm run riders`.", "",
    `${rows.filter(r => r.authored).length} of ${rows.length} authored.`, ""];
  for ( const g of groups ) {
    const list = rows.filter(r => r.group === g);
    out.push(`## ${g} (${list.filter(r => r.authored).length}/${list.length})`, "", "| Level | Feature | Identifier | Rider | Trigger text |", "| --- | --- | --- | --- | --- |");
    for ( const r of list ) out.push(`| ${r.level || "—"} | ${r.name} | \`${r.id}\` | ${r.authored ? "yes" : ""} | ${r.line.replace(/\|/g, "/")} |`);
    out.push("");
  }
  fs.mkdirSync(path.join(ROOT, "docs/generated"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, "docs/generated/rider-coverage.md"), out.join("\n"));
  console.log(`docs/generated/rider-coverage.md: ${rows.filter(r => r.authored).length}/${rows.length} authored across ${groups.length} groups`);
}
